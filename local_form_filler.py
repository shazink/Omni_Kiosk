class ConversationalSlotExtractor:
    """
    On-device deterministic multi-slot conversational extractor.
    Extracts multiple field values from a single natural narrative statement.
    Works 100% offline with zero external cloud dependencies or API keys.
    """

    KNOWN_DISTRICTS = [
        "Thiruvananthapuram", "Ernakulam", "Kozhikode", "Thrissur", "Kannur",
        "Kollam", "Alappuzha", "Pathanamthitta", "Kottayam", "Idukki",
        "Palakkad", "Malappuram", "Wayanad", "Kasaragod"
    ]

    KNOWN_TALUKS = [
        "Neyyattinkara", "Nedumangad", "Kattakada", "Chirayinkeezhu", "Varkala",
        "Aluva", "Kanayannur", "Kochi", "Kothamangalam", "Kunnathunad", "Muvattupuzha", "North Paravur",
        "Koyilandy", "Thamarassery", "Vadakara", "Chalakudy", "Kodungallur", "Mukundapuram",
        "Taliparamba", "Payyanur", "Iritty", "Thalassery"
    ]

    KNOWN_VILLAGES = [
        "Nemom", "Athiyannoor", "Balaramapuram", "Chenkal", "Kanjiramkulam",
        "Karumkulam", "Kulathoor", "Parassala", "Poovar", "Vizhinjam",
        "Edappally", "Kadavanthra", "Poonithura", "Vyttila", "Kasaba", "Kakkodi", "Olavanna"
    ]

    KNOWN_PURPOSES = [
        ("higher education", "Higher Education"),
        ("college scholarship", "Scholarship"),
        ("scholarship", "Scholarship"),
        ("housing scheme", "Housing Scheme"),
        ("housing", "Housing Scheme"),
        ("general", "General"),
    ]

    def __init__(self, schema: Optional[FormSchema] = None):
        self.schema = schema

    def extract_slots(self, utterance: str) -> Dict[str, Any]:
        """
        Extracts structured form fields from conversational text.
        Supports multi-slot utterances such as:
        "My name is Arun Kumar, my ration card number is 2451098, and my annual family income is 75000 rupees for my college scholarship."
        """
        if not utterance or not utterance.strip():
            return {}

        results: Dict[str, Any] = {}
        text = utterance.strip()
        text_lower = text.lower()

        # 1. Extract Full Name
        # e.g., "My name is Arun Kumar...", "I am Arun Kumar...", "Name: Arun Kumar"
        name_match = re.search(
            r"(?:my\s+name\s+is|i\s+am|applicant(?:\s+name)?(?:\s+is)?)\s+([A-Za-z\s\.]+?)(?:,|\.|\band\b|\bmy\b|\bration\b|\bincome\b|\bfor\b|\bwith\b|$)",
            text,
            re.IGNORECASE
        )
        if name_match:
            candidate_name = name_match.group(1).strip()
            # Clean up common stray words
            candidate_name = re.sub(r"^(mr\.?|mrs\.?|ms\.?|dr\.?)\s+", "", candidate_name, flags=re.IGNORECASE)
            if len(candidate_name.split()) >= 1 and not any(w in candidate_name.lower() for w in ["annual", "income", "ration"]):
                results["txtApplicantName"] = candidate_name
                results["applicantName"] = candidate_name

        # 2. Extract Aadhaar Number (12 digits)
        aadhaar_match = re.search(r"\b(\d{4}\s?\d{4}\s?\d{4})\b", text)
        if aadhaar_match:
            raw_uid = re.sub(r"\s+", "", aadhaar_match.group(1))
            if len(raw_uid) == 12:
                results["txtAadhaarNo"] = raw_uid
                results["aadhaarNo"] = raw_uid

        # 3. Extract Ration Card Number
        ration_match = re.search(
            r"(?:ration\s*card(?:\s*no|\s*number)?(?:\s*is)?)\s*[:=]?\s*([A-Za-z0-9\-_]+)",
            text,
            re.IGNORECASE
        )
        if ration_match:
            results["txtRationCardNo"] = ration_match.group(1).strip()

        # 4. Extract Annual Income
        # Patterns:
        # "annual income is 85000", "family income is 75,000 rupees", "income of 85000"
        income_match = re.search(
            r"(?:annual(?:\s+family)?\s+income(?:\s+is)?|family\s+income(?:\s+is)?|income(?:\s+is|\s+of)?)\s*[:=]?\s*(?:rs\.?|inr|rupees)?\s*([0-9]+(?:,[0-9]+)*)",
            text,
            re.IGNORECASE
        )
        if not income_match:
            # Reverse pattern: "75000 rupees for my college scholarship"
            income_match = re.search(
                r"\b([0-9]{4,8})\s*(?:rupees|rs\.?|inr)\b",
                text,
                re.IGNORECASE
            )

        if income_match:
            clean_income = income_match.group(1).replace(",", "").strip()
            results["txtAnnualIncome"] = clean_income

        # 5. Extract Purpose (matches known options or schema select options)
        purpose_candidates = self.KNOWN_PURPOSES
        if self.schema:
            purpose_field = self.schema.get_field("ddlPurpose")
            if purpose_field and purpose_field.options:
                purpose_candidates = [(opt.lower(), opt) for opt in purpose_field.options]

        for trigger, canonical in purpose_candidates:
            if re.search(rf"\b{re.escape(trigger)}\b", text_lower):
                results["ddlPurpose"] = canonical
                break

        # If not matched yet, check for pattern "purpose is X"
        if "ddlPurpose" not in results:
            p_match = re.search(r"(?:purpose\s+is|for(?:\s+my)?)\s+([A-Za-z\s]+?)(?:,|\.|\band\b|$)", text, re.IGNORECASE)
            if p_match:
                p_text = p_match.group(1).strip().title()
                results["ddlPurpose"] = p_text

        # 6. Extract District / Taluk / Village
        # Districts
        for d in self.KNOWN_DISTRICTS:
            if re.search(rf"\b{re.escape(d)}\b", text, re.IGNORECASE):
                results["ddlDistrict"] = d
                break

        # Taluks
        for t in self.KNOWN_TALUKS:
            if re.search(rf"\b{re.escape(t)}\b", text, re.IGNORECASE):
                results["ddlTaluk"] = t
                break

        # Villages
        for v in self.KNOWN_VILLAGES:
            if re.search(rf"\b{re.escape(v)}\b", text, re.IGNORECASE):
                results["ddlVillage"] = v
                break

        # 7. Additional Civic Fields (Disability, Bank, IFSC)
        ifsc_match = re.search(r"\b([A-Z]{4}0[A-Z0-9]{6})\b", text)
        if ifsc_match:
            results["ifscCode"] = ifsc_match.group(1)

        disability_pct = re.search(r"\b([0-9]{1,3})\s*%\s*(?:disability)?\b", text, re.IGNORECASE)
        if disability_pct:
            results["disabilityPercent"] = disability_pct.group(1)

        logger.info(f"Extracted {len(results)} slot(s) from narrative: {list(results.keys())}")
        return results


