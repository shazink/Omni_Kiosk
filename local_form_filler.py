class FieldSource(str, Enum):
    OCR = "ocr"
    CONVERSATION = "conversation"
    SIGN_TOKENS = "sign_tokens"
    DEFAULT = "default"
    USER_OVERRIDE = "user_override"


@dataclass
class FormField:
    """Specification of an individual form input field from Module 2 schema."""
    id: str
    type: str  # text, number, select, file, radio, checkbox, textarea
    label: str = ""
    required: bool = False
    pattern: Optional[str] = None
    min: Optional[str] = None
    max: Optional[str] = None
    options: List[str] = field(default_factory=list)
    accept: Optional[str] = None

    @classmethod
    def from_dict(cls, data: Dict[str, Any]) -> FormField:
        return cls(
            id=str(data.get("id", "")),
            type=str(data.get("type", "text")).lower(),
            label=str(data.get("label", data.get("id", ""))),
            required=bool(data.get("required", False)),
            pattern=data.get("pattern"),
            min=data.get("min"),
            max=data.get("max"),
            options=[str(opt) for opt in data.get("options", [])],
            accept=data.get("accept"),
        )


@dataclass
class FormSchema:
    """Encapsulates the current form schema handed off by Module 2."""
    service_name: str
    form_url: str
    fields: List[FormField] = field(default_factory=list)
    downloaded_docs: List[str] = field(default_factory=list)

    def get_field(self, field_id: str) -> Optional[FormField]:
        for f in self.fields:
            if f.id == field_id:
                return f
        return None

    @classmethod
    def from_dict(cls, data: Dict[str, Any]) -> FormSchema:
        if "form_url" not in data:
            raise FormSchemaError("Schema is missing mandatory 'form_url' attribute.")
        fields_raw = data.get("fields", [])
        if not isinstance(fields_raw, list):
            raise FormSchemaError("Schema 'fields' must be a list.")
        fields = [FormField.from_dict(f) for f in fields_raw if isinstance(f, dict)]
        return cls(
            service_name=str(data.get("service_name", "Civic Service Form")),
            form_url=str(data["form_url"]),
            fields=fields,
            downloaded_docs=[str(d) for d in data.get("downloaded_docs", [])],
        )


@dataclass
class FieldValue:
    """Holds a structured value for a field along with provenance."""
    value: Any
    source: FieldSource
    timestamp: str = field(default_factory=lambda: datetime.datetime.now().isoformat())
    metadata: Dict[str, Any] = field(default_factory=dict)


@dataclass
class ConflictRecord:
    """Records conflicting data points between OCR and conversational input."""
    field_id: str
    existing_value: Any
    existing_source: FieldSource
    incoming_value: Any
    incoming_source: FieldSource
    resolved_value: Any
    resolution_reason: str


@dataclass
class FormFillingResult:
    """Structured report returned after Playwright DOM population and verification."""
    status: str  # POPULATED, PARTIALLY_POPULATED, FAILED
    form_url: str
    fields_populated: List[str] = field(default_factory=list)
    fields_missing: List[str] = field(default_factory=list)
    validation_errors: List[str] = field(default_factory=list)
    dom_values: Dict[str, Any] = field(default_factory=dict)
    conflicts: List[Dict[str, Any]] = field(default_factory=list)

    def to_dict(self) -> Dict[str, Any]:
        return asdict(self)


