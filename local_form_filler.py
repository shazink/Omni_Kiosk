# SUPERVISOR AGENT (HUMAN-IN-THE-LOOP INTERLOCK GATE)
# ==============================================================================

class SupervisorAgent:
    """
    Human-in-the-Loop circuit breaker for final submission verification.
    Architecturally blocks automated submission without explicit confirmation.
    Generates multimodal pre-submit summary (Audio readback or High-Contrast visual card).
    """

    def __init__(self):
        self._is_locked: bool = True
        self._execution_token: Optional[str] = None

    def generate_summary(self, state_dict: Dict[str, Any]) -> Tuple[str, Dict[str, Any]]:
        """
        Generates:
        1. Directional TTS spoken summary string for blind/low-vision citizens.
        2. High-contrast visual review card for deaf/sign language citizens.
        """
        name = state_dict.get("txtApplicantName") or state_dict.get("applicantName") or "Applicant"
        aadhaar = state_dict.get("txtAadhaarNo") or state_dict.get("aadhaarNo") or ""
        masked_aadhaar = f"ending in {aadhaar[-4:]}" if len(aadhaar) >= 4 else "provided"
        income = state_dict.get("txtAnnualIncome") or "stated"
        district = state_dict.get("ddlDistrict") or "selected district"
        purpose = state_dict.get("ddlPurpose") or "Income Certificate"

        spoken_summary = (
            f"Please verify your application details: Name {name}, Aadhaar {masked_aadhaar}, "
            f"Annual income {income} rupees for {purpose}, located in {district}. "
            f"Please say 'Submit' or give a Thumbs-Up gesture to confirm."
        )

        visual_card = {
            "title": "Review Application Details",
            "applicant_name": name,
            "aadhaar_masked": mask_pii_value("aadhaar", aadhaar),
            "annual_income": f"Rs. {income}",
            "district": district,
            "purpose": purpose,
            "action_prompt": "Show Thumbs-Up gesture or press Submit to confirm.",
            "theme": "HIGH_CONTRAST_DARK",
            "border_color": "#FFE600",
            "background": "#000000",
        }

        return spoken_summary, visual_card

    def process_confirmation(self, signal: str) -> bool:
        """
        Processes human confirmation signal.
        Accepts: 'Submit', 'Confirm', 'yes', 'THUMBS_UP'.
        Rejects: 'Cancel', 'Open_Palm', 'no'.
        """
        sig = signal.strip().lower()
        valid_confirmations = ["submit", "confirm", "yes", "thumbs_up", "thumbs-up", "confirmed"]

        if any(c in sig for c in valid_confirmations):
            self._is_locked = False
            self._execution_token = f"EXEC_TOKEN_{datetime.datetime.now().strftime('%Y%m%d%H%M%S%f')}"
            logger.info(f"Supervisor Agent: Human confirmation verified. Token issued: {self._execution_token}")
            return True
        else:
            self._is_locked = True
            self._execution_token = None
            logger.warning(f"Supervisor Agent: Submission rejected or cancelled via signal '{signal}'.")
            return False

    def is_unlocked(self) -> bool:
        return not self._is_locked and self._execution_token is not None

    def get_token(self) -> Optional[str]:
        return self._execution_token


# ==============================================================================
# EPHEMERAL PURGE (SECURE VOLATILE MEMORY ZEROIZATION)
# ==============================================================================

class EphemeralPurge:
    """
    Cryptographic volatile memory zeroization and ephemeral session purge.
    Overwrites sensitive RAM buffers with zeros and terminates Playwright browser sessions.
    """

    @staticmethod
    def zeroize_bytes(b: Union[bytes, bytearray]) -> bytearray:
        """Zeroizes a mutable bytearray in RAM."""
        ba = bytearray(b)
        for i in range(len(ba)):
            ba[i] = 0
        return ba

    @classmethod
    def purge_state_manager(cls, state_mgr: FormStateManager) -> None:
        """Overwrites and purges all document buffers, fields, and conflicts from RAM."""
        # Overwrite all file buffers with zeros
        for fid, (fname, mtype, fbuf) in list(state_mgr.file_buffers.items()):
            zeroed = cls.zeroize_bytes(fbuf)
            del fbuf
            state_mgr.file_buffers[fid] = (fname, mtype, bytes(zeroed))

        state_mgr.file_buffers.clear()
        state_mgr.fields_state.clear()
        state_mgr.conflicts.clear()
        logger.info("EphemeralPurge: Volatile RAM buffers and state dictionary successfully zeroized.")

    @classmethod
    def purge_filler(cls, filler: LocalFormFiller) -> None:
        """Complete purge of filler state and browser context."""
        if filler.state_mgr:
            cls.purge_state_manager(filler.state_mgr)
        filler.close()
        logger.info("EphemeralPurge: LocalFormFiller session terminated and cleaned.")
