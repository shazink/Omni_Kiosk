class SpeechEngine:
    """
    Directional Audio & TTS abstraction for Blind / Low-Vision citizens.
    Can be connected to Module 4's TTS pipeline or fallback to safe logging.
    """
    def __init__(self, callback: Optional[Callable[[str], None]] = None):
        self.callback = callback

    def speak(self, text: str) -> None:
        safe_text = redact_text_pii(text)
        logger.info(f"[SpeechEngine / TTS Readback] \"{safe_text}\"")
        if self.callback:
            try:
                self.callback(text)
            except Exception as e:
                logger.warning(f"SpeechEngine callback error: {e}")


class VisualPromptEngine:
    """
    Visual Card & High-Contrast abstraction for Deaf / Non-Verbal citizens.
    Exposes high-visibility prompt cards for the kiosk UI.
    """
    @staticmethod
    def create_card(field: FormField, prompt_text: str) -> Dict[str, Any]:
        return {
            "field_id": field.id,
            "field_label": field.label,
            "field_type": field.type,
            "required": field.required,
            "prompt": prompt_text,
            "options": field.options if field.type == "select" else [],
            "theme": "HIGH_CONTRAST_DARK",
            "border_color": "#FFE600",
            "background": "#000000",
        }


