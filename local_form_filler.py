class LocalFormFiller:
    """
    Main controller for OmniKiosk Module 5.
    Coordinates schema loading, conversational parsing, state merging,
    accessibility readback, and autonomous Playwright DOM injection.
    """

    def __init__(
        self,
        schema_path: Optional[Union[str, Path]] = None,
        schema_dict: Optional[Dict[str, Any]] = None,
        speech_callback: Optional[Callable[[str], None]] = None,
    ):
        self.schema: Optional[FormSchema] = None
        self.state_mgr: Optional[FormStateManager] = None
        self.slot_extractor: Optional[ConversationalSlotExtractor] = None
        self.dom_injector = DOMInjector()
        self.speech_engine = SpeechEngine(callback=speech_callback)
        self.critic_agent = CriticAgent()
        self.supervisor_agent = SupervisorAgent()
        self.ephemeral_purge = EphemeralPurge()
        self.edge_slm: Optional[EdgeSLM] = None
        self._current_field_index: int = 0

        # Playwright internal handles
        self._pw_instance = None
        self._browser: Optional[Browser] = None
        self._context: Optional[BrowserContext] = None
        self._page: Optional[Page] = None

        if schema_path:
            self.load_schema_from_file(schema_path)
        elif schema_dict:
            self.load_schema_from_dict(schema_dict)

    def load_schema_from_file(self, file_path: Union[str, Path]) -> FormSchema:
        """Loads and parses current_form_schema.json."""
        p = Path(file_path)
        if not p.exists():
            raise FormSchemaError(f"Form schema file '{file_path}' does not exist.")
        try:
            with open(p, "r", encoding="utf-8") as f:
                data = json.load(f)
            return self.load_schema_from_dict(data)
        except json.JSONDecodeError as e:
            raise FormSchemaError(f"Malformed JSON in schema file '{file_path}': {e}") from e

    def load_schema_from_dict(self, data: Dict[str, Any]) -> FormSchema:
        """Loads schema from dictionary payload."""
        self.schema = FormSchema.from_dict(data)
        self.state_mgr = FormStateManager(self.schema)
        self.slot_extractor = ConversationalSlotExtractor(self.schema)
        self.edge_slm = EdgeSLM(self.schema)
        self._current_field_index = 0
        logger.info(f"Loaded schema '{self.schema.service_name}' with {len(self.schema.fields)} fields.")
        return self.schema

    def load_ocr_data(self, ocr_payload: Dict[str, Any]) -> None:
        """Consumes OCR payload and in-memory document buffer from Module 3."""
        if not self.state_mgr:
            raise FormFillerError("Schema must be loaded before ingesting OCR data.")
        self.state_mgr.load_ocr_data(ocr_payload)

    def extract_slots(self, utterance: str) -> Dict[str, Any]:
        """Extracts structured form fields from natural conversational utterance."""
        if not self.slot_extractor:
            self.slot_extractor = ConversationalSlotExtractor(self.schema)
        return self.slot_extractor.extract_slots(utterance)

    def merge_inputs(self, conversational_slots: Dict[str, Any], source: FieldSource = FieldSource.CONVERSATION) -> None:
        """Merges conversational slots into current form state."""
        if not self.state_mgr:
            raise FormFillerError("Schema must be loaded before merging inputs.")
        self.state_mgr.merge_inputs(conversational_slots, source=source)

    def get_next_field(self) -> Optional[FormField]:
        """Returns the next required field that still needs input."""
        if not self.state_mgr or not self.schema:
            return None
        unfilled = self.state_mgr.get_unfilled_required_fields()
        return unfilled[0] if unfilled else None

    def generate_prompt(self, field: Optional[FormField] = None) -> str:
        """Generates a contextual spoken/visual prompt for the active field."""
        target_field = field or self.get_next_field()
        if not target_field:
            return "All required fields have been gathered. Ready for verification."
        prompt = FieldPromptEngine.generate_prompt(target_field)
        self.speech_engine.speak(prompt)
        return prompt

    def get_visual_card(self, field: Optional[FormField] = None) -> Dict[str, Any]:
        """Returns high-contrast visual display card for Deaf mode."""
        target_field = field or self.get_next_field()
        if not target_field:
            return {"status": "COMPLETE", "prompt": "All fields gathered."}
        prompt = FieldPromptEngine.generate_prompt(target_field)
        return VisualPromptEngine.create_card(target_field, prompt)

    def get_state(self) -> Dict[str, Any]:
        """Returns structured dictionary of currently gathered form state."""
        if not self.state_mgr:
            return {}
        return self.state_mgr.get_structured_dict()

    def get_conflicts(self) -> List[Dict[str, Any]]:
        """Returns list of detected data conflicts for Module 6 governance."""
        if not self.state_mgr:
            return []
        return [asdict(c) for c in self.state_mgr.conflicts]

    def populate_form(
        self,
        page: Optional[Page] = None,
        headless: bool = True,
        slow_mo: int = 0,
        portal_base_url: Optional[str] = None
    ) -> FormFillingResult:
        """
        Executes autonomous Playwright DOM injection on the live civic portal.
        Populates text, numbers, dropdowns, cascading selections, and in-memory files.
        Verifies populated state and hands off cleanly without clicking submit.
        """
        if not self.schema or not self.state_mgr:
            raise FormFillerError("Schema and state manager must be initialized before DOM injection.")

        if not PLAYWRIGHT_AVAILABLE:
            raise BrowserAutomationError(
                "Playwright is not installed. Please run: pip install playwright && playwright install chromium"
            )

        close_after = False
        if page is not None:
            self._page = page
            self.dom_injector.set_page(page)
        else:
            self._pw_instance = sync_playwright().start()
            self._browser = self._pw_instance.chromium.launch(headless=headless, slow_mo=slow_mo)
            self._context = self._browser.new_context()
            self._page = self._context.new_page()
            self.dom_injector.set_page(self._page)
            close_after = False  # Keep page alive for Module 6 to inspect

        # Determine target URL
        target_url = self.schema.form_url
        if portal_base_url:
            # Allow overriding localhost:3000 during test fixtures
            if "/forms/" in target_url:
                rel_path = target_url[target_url.find("/forms/"):]
                target_url = f"{portal_base_url.rstrip('/')}{rel_path}"

        # Navigate to target form
        self.dom_injector.navigate(target_url)

        # Plan injection order:
        # Group cascading dropdowns (ddlDistrict -> ddlTaluk -> ddlVillage)
        populated_field_ids = set()
        state = self.state_mgr.fields_state

        # Check for cascading district/taluk/village sequence
        has_cascade = any(f.id in state for f in [self.schema.get_field("ddlDistrict"), self.schema.get_field("ddlTaluk")])
        if "ddlDistrict" in state and "ddlTaluk" in state:
            dist_val = state["ddlDistrict"].value
            taluk_val = state["ddlTaluk"].value
            self.dom_injector.select_cascading_dropdown(
                "#ddlDistrict", str(dist_val),
                "#ddlTaluk", str(taluk_val)
            )
            populated_field_ids.add("ddlDistrict")
            populated_field_ids.add("ddlTaluk")

            if "ddlVillage" in state:
                village_val = state["ddlVillage"].value
                self.dom_injector.select_cascading_dropdown(
                    "#ddlTaluk", str(taluk_val),
                    "#ddlVillage", str(village_val)
                )
                populated_field_ids.add("ddlVillage")

        # Populate remaining fields from state
        for field_id, field_val in state.items():
            if field_id in populated_field_ids:
                continue

            field_spec = self.schema.get_field(field_id)
            if not field_spec:
                continue

            selector = f"#{field_id}"
            val = field_val.value

            if field_spec.type == "text" or field_spec.type == "textarea":
                self.dom_injector.fill_text(selector, str(val))
                populated_field_ids.add(field_id)

            elif field_spec.type == "number":
                self.dom_injector.fill_number(selector, val, min_val=field_spec.min, max_val=field_spec.max)
                populated_field_ids.add(field_id)

            elif field_spec.type == "select":
                self.dom_injector.select_dropdown(selector, str(val))
                populated_field_ids.add(field_id)

        # Handle in-memory file uploads
        for file_field_id, (fname, mtype, fbuf) in self.state_mgr.file_buffers.items():
            selector = f"#{file_field_id}"
            self.dom_injector.upload_in_memory_file(selector, fname, mtype, fbuf)
            populated_field_ids.add(file_field_id)

        # Post-injection verification
        verification_result = self.dom_injector.verify_dom_state(self.schema, self.state_mgr)
        logger.info(
            f"DOM Injection complete. Status: {verification_result.status}, "
            f"Populated: {len(verification_result.fields_populated)}, "
            f"Missing: {len(verification_result.fields_missing)}"
        )

        return verification_result

    def close(self) -> None:
        """Closes internal browser context and releases Playwright resources."""
        try:
            if self._context:
                self._context.close()
            if self._browser:
                self._browser.close()
            if self._pw_instance:
                self._pw_instance.stop()
        except Exception as e:
            logger.warning(f"Error during browser teardown: {e}")
        finally:
            self._context = None
            self._browser = None
            self._page = None
            self._pw_instance = None


