class FormStateManager:
    """
    Maintains local private form state, merges OCR and conversational inputs,
    and tracks provenance and conflict records.
    """
    def __init__(self, schema: FormSchema):
        self.schema = schema
        self.fields_state: Dict[str, FieldValue] = {}
        self.file_buffers: Dict[str, Tuple[str, str, bytes]] = {}  # field_id -> (filename, mimetype, bytes)
        self.conflicts: List[ConflictRecord] = []

    def load_ocr_data(self, ocr_payload: Dict[str, Any]) -> None:
        """
        Consumes structured OCR output from Module 3.
        Maps document fields to schema and stores in-memory document buffer.
        """
        if not ocr_payload:
            return

        extracted = ocr_payload.get("extracted_data", {})
        full_name = extracted.get("full_name")
        aadhaar_no = extracted.get("aadhaar_number")
        dob = extracted.get("dob")

        if full_name:
            # Map to both standard ID conventions
            for fid in ["txtApplicantName", "applicantName"]:
                if self.schema.get_field(fid):
                    self.set_value(fid, full_name, FieldSource.OCR, metadata={"confidence": ocr_payload.get("sharpness_score", 1.0)})

        if aadhaar_no:
            clean_uid = re.sub(r"\s+", "", str(aadhaar_no))
            for fid in ["txtAadhaarNo", "aadhaarNo"]:
                if self.schema.get_field(fid):
                    self.set_value(fid, clean_uid, FieldSource.OCR)

        if dob:
            for fid in ["txtDob", "dob"]:
                if self.schema.get_field(fid):
                    self.set_value(fid, dob, FieldSource.OCR)

        # Handle in-memory document image buffer
        img_buffer = ocr_payload.get("image_buffer")
        if img_buffer:
            if isinstance(img_buffer, (bytes, bytearray)):
                self.attach_file_buffer("fileAadhaar", "aadhaar_card_scanned.png", "image/png", bytes(img_buffer))
            elif isinstance(img_buffer, str):
                # If encoded as utf-8 or mock string
                self.attach_file_buffer("fileAadhaar", "aadhaar_card_scanned.png", "image/png", img_buffer.encode("utf-8"))

        logger.info(
            f"Loaded OCR payload into state. Applicant: {mask_pii_value('name', full_name)}, "
            f"UID: {mask_pii_value('aadhaar', aadhaar_no)}"
        )

    def attach_file_buffer(self, field_id: str, filename: str, mimetype: str, buffer_bytes: bytes) -> None:
        """Attaches an in-memory document file buffer without saving to disk."""
        if not isinstance(buffer_bytes, (bytes, bytearray)):
            raise FileInjectionError(f"Buffer for '{field_id}' must be bytes-like object.")
        if len(buffer_bytes) == 0:
            raise FileInjectionError(f"Buffer for '{field_id}' cannot be empty.")
        self.file_buffers[field_id] = (filename, mimetype, bytes(buffer_bytes))
        self.set_value(field_id, f"[RAM_BUFFER: {filename} ({len(buffer_bytes)} bytes)]", FieldSource.OCR)
        logger.info(f"Attached in-memory file buffer to #{field_id}: {filename} ({len(buffer_bytes)} bytes)")

    def set_value(self, field_id: str, value: Any, source: FieldSource, metadata: Optional[Dict[str, Any]] = None) -> None:
        """Stores or updates a field value with source tracking."""
        self.fields_state[field_id] = FieldValue(
            value=value,
            source=source,
            metadata=metadata or {}
        )

    def merge_inputs(self, conversational_slots: Dict[str, Any], source: FieldSource = FieldSource.CONVERSATION) -> None:
        """
        Merges conversational slot inputs with existing state.
        Precedence Rules:
        - Verified OCR identity (Aadhaar number) has high authority; conflicting spoken
          Aadhaar numbers are flagged in `conflicts` rather than silently discarding.
        - Conversational statements populate unfilled fields or user-declarative fields (income, purpose, district).
        """
        for field_id, new_val in conversational_slots.items():
            if not self.schema.get_field(field_id):
                # Try finding alternative ID in schema (e.g. txtApplicantName vs applicantName)
                alt_field = None
                for f in self.schema.fields:
                    if f.id.lower() == field_id.lower():
                        alt_field = f
                        break
                if not alt_field:
                    continue
                field_id = alt_field.id

            existing = self.fields_state.get(field_id)
            if existing is None:
                self.set_value(field_id, new_val, source)
                logger.info(f"Set #{field_id} from {source.value}: {mask_pii_value(field_id, new_val)}")
            else:
                # Value already exists, check for conflict
                if str(existing.value).strip() != str(new_val).strip():
                    if existing.source == FieldSource.OCR and "aadhaar" in field_id.lower():
                        # OCR Aadhaar has precedence; flag conflict
                        conflict = ConflictRecord(
                            field_id=field_id,
                            existing_value=existing.value,
                            existing_source=existing.source,
                            incoming_value=new_val,
                            incoming_source=source,
                            resolved_value=existing.value,
                            resolution_reason="Preserved verified OCR document identity; flagged conflict for Module 6 audit."
                        )
                        self.conflicts.append(conflict)
                        logger.warning(
                            f"Discrepancy in #{field_id}: OCR had {mask_pii_value(field_id, existing.value)} "
                            f"but conversational input said {mask_pii_value(field_id, new_val)}."
                        )
                    else:
                        # User conversational input overrides default or updates state
                        self.set_value(field_id, new_val, source)
                        logger.info(f"Updated #{field_id} with {source.value}: {mask_pii_value(field_id, new_val)}")

    def get_unfilled_required_fields(self) -> List[FormField]:
        """Returns list of mandatory schema fields that have not yet been populated."""
        unfilled = []
        for f in self.schema.fields:
            if not f.required:
                continue
            if f.type == "file":
                if f.id not in self.file_buffers:
                    unfilled.append(f)
            else:
                if f.id not in self.fields_state or self.fields_state[f.id].value is None:
                    unfilled.append(f)
        return unfilled

    def get_structured_dict(self) -> Dict[str, Any]:
        """Returns clean dictionary of populated field IDs and values."""
        return {fid: fval.value for fid, fval in self.fields_state.items()}


