# CRITIC AGENT (PRE-SUBMISSION VERIFICATION GUARDRAIL)
# ==============================================================================

class CriticAgent:
    """
    Critic Verification Guardrail for pre-submission form validation.
    Performs regex audit (12-digit Aadhaar, positive income, mandatory fields,
    discrepancy detection between OCR document and conversational spoken data).
    """

    @staticmethod
    def validate_aadhaar_checksum(aadhaar: str) -> bool:
        """Validates 12-digit Aadhaar pattern."""
        clean = re.sub(r"\D", "", str(aadhaar))
        return bool(re.fullmatch(r"[0-9]{12}", clean))

    @staticmethod
    def calculate_string_similarity(s1: str, s2: str) -> float:
        """Computes simple Levenshtein-like character overlap ratio for name discrepancy checks."""
        w1 = set(s1.lower().split())
        w2 = set(s2.lower().split())
        if not w1 or not w2:
            return 0.0
        overlap = len(w1.intersection(w2))
        return overlap / max(len(w1), len(w2))

    def audit_state(
        self,
        schema: FormSchema,
        state_mgr: FormStateManager
    ) -> Tuple[bool, List[str]]:
        """
        Runs comprehensive pre-submission audit against current state.
        Returns (is_valid, list_of_errors_or_warnings).
        """
        errors: List[str] = []
        state = state_mgr.fields_state

        for field_spec in schema.fields:
            fid = field_spec.id
            if field_spec.required:
                if field_spec.type == "file":
                    if fid not in state_mgr.file_buffers:
                        errors.append(f"Missing mandatory file buffer for #{fid}.")
                else:
                    if fid not in state or state[fid].value is None or str(state[fid].value).strip() == "":
                        errors.append(f"Missing mandatory field #{fid} ({field_spec.label}).")

        # 1. Aadhaar UID Syntax check
        for uid_key in ["txtAadhaarNo", "aadhaarNo"]:
            if uid_key in state and state[uid_key].value:
                val = str(state[uid_key].value)
                if not self.validate_aadhaar_checksum(val):
                    errors.append(f"Invalid Aadhaar syntax for #{uid_key}: expected exactly 12 digits.")

        # 2. Annual Income positive numeric check
        if "txtAnnualIncome" in state and state["txtAnnualIncome"].value is not None:
            try:
                income_val = float(str(state["txtAnnualIncome"].value).replace(",", ""))
                if income_val <= 0:
                    errors.append(f"Annual income must be a positive number greater than 0, got {income_val}.")
            except ValueError:
                errors.append("Annual income is not a valid number.")

        # 3. Mandatory Cascading dropdown checks
        for ddl_key in ["ddlDistrict", "ddlTaluk", "ddlVillage"]:
            if ddl_key in state:
                val = str(state[ddl_key].value)
                if not val or val.startswith("--"):
                    errors.append(f"Dropdown #{ddl_key} is on unselected/placeholder value.")

        # 4. Discrepancy checks (Spoken name vs OCR document name)
        for name_key in ["txtApplicantName", "applicantName"]:
            if name_key in state:
                fval = state[name_key]
                if fval.source == FieldSource.CONVERSATION and state_mgr.conflicts:
                    for c in state_mgr.conflicts:
                        if c.field_id == name_key:
                            sim = self.calculate_string_similarity(str(c.existing_value), str(c.incoming_value))
                            if sim < 0.5:
                                errors.append(
                                    f"Discrepancy detected in applicant name: OCR document has "
                                    f"'{mask_pii_value('name', c.existing_value)}' but conversational input stated "
                                    f"'{mask_pii_value('name', c.incoming_value)}'."
                                )

        is_valid = len(errors) == 0
        return is_valid, errors


