class DOMInjector:
    """
    Autonomous Playwright DOM population engine.
    Injects text, numbers, dropdown options, cascading selections, and in-memory files.
    Dispatches HTML5 input/change events and verifies post-injection state.
    Module 5 NEVER autonomously clicks the final submit button.
    """

    def __init__(self, page: Optional[Page] = None):
        self.page = page

    def set_page(self, page: Page) -> None:
        self.page = page

    def navigate(self, form_url: str, timeout_ms: int = 15000) -> None:
        """Navigates to the civic portal form URL."""
        if not self.page:
            raise BrowserAutomationError("Playwright page instance is not initialized.")
        try:
            logger.info(f"Navigating to civic portal: {form_url}")
            self.page.goto(form_url, timeout=timeout_ms, wait_until="load")
        except Exception as e:
            raise BrowserAutomationError(f"Failed to navigate to '{form_url}': {e}") from e

    def fill_text(self, selector: str, value: str) -> None:
        """Fills a text/textarea field and triggers input and change events."""
        if not self.page:
            raise BrowserAutomationError("Playwright page not set.")
        try:
            loc = self.page.locator(selector)
            loc.wait_for(state="visible", timeout=5000)
            loc.fill(value)
            loc.dispatch_event("input")
            loc.dispatch_event("change")
        except Exception as e:
            raise FieldNotFoundError(f"Failed to fill text into '{selector}': {e}") from e

    def fill_number(self, selector: str, value: Union[int, float, str], min_val: Optional[str] = None, max_val: Optional[str] = None) -> None:
        """Fills a numeric input field with bounds checking."""
        val_str = str(value).replace(",", "").strip()
        try:
            num = float(val_str)
            if min_val is not None and num < float(min_val):
                raise FieldValidationError(f"Value {num} for '{selector}' is below minimum {min_val}.")
            if max_val is not None and num > float(max_val):
                raise FieldValidationError(f"Value {num} for '{selector}' exceeds maximum {max_val}.")
        except ValueError:
            raise FieldValidationError(f"Invalid numeric input '{val_str}' for field '{selector}'.")

        if not self.page:
            raise BrowserAutomationError("Playwright page not set.")

        int_or_float_str = str(int(num)) if num.is_integer() else str(num)
        self.fill_text(selector, int_or_float_str)

    def select_dropdown(self, selector: str, value: str) -> None:
        """Selects a value in a standard <select> dropdown, validating available options."""
        if not self.page:
            raise BrowserAutomationError("Playwright page not set.")
        loc = self.page.locator(selector)
        try:
            loc.wait_for(state="visible", timeout=5000)
        except Exception as e:
            raise FieldNotFoundError(f"Dropdown '{selector}' not found or not visible: {e}") from e

        # Inspect available options
        options_info = self.page.eval_on_selector(
            selector,
            """el => Array.from(el.options).map(o => ({ value: o.value, text: o.text }))"""
        )
        matched_val = None
        for opt in options_info:
            if opt["value"].strip().lower() == value.strip().lower() or opt["text"].strip().lower() == value.strip().lower():
                matched_val = opt["value"]
                break

        if matched_val is None:
            available = [f"{o['text']} ({o['value']})" for o in options_info if o['value']]
            raise DropdownOptionNotFoundError(
                f"Requested option '{value}' not found in dropdown '{selector}'. Available: {available}"
            )

        try:
            loc.select_option(value=matched_val)
            loc.dispatch_event("input")
            loc.dispatch_event("change")
        except Exception as e:
            raise BrowserAutomationError(f"Error selecting option in '{selector}': {e}") from e

    def select_cascading_dropdown(
        self,
        parent_selector: str,
        parent_value: str,
        child_selector: str,
        child_value: str,
        timeout_ms: int = 6000
    ) -> None:
        """
        Handles dependent cascading dropdowns (e.g. District -> Taluk -> Village).
        1. Selects parent option.
        2. Waits until child dropdown options are dynamically populated.
        3. Validates that requested child option exists.
        4. Selects child option.
        """
        if not self.page:
            raise BrowserAutomationError("Playwright page not set.")

        logger.info(f"Cascading dropdown: Setting parent {parent_selector}='{parent_value}' -> {child_selector}='{child_value}'")
        # Step 1: Select parent
        self.select_dropdown(parent_selector, parent_value)

        # Step 2: Wait for child options to be populated (length > 1, ignoring default placeholder)
        child_clean_id = child_selector.replace("#", "")
        js_wait_condition = f"""
            () => {{
                const el = document.getElementById('{child_clean_id}') || document.querySelector('{child_selector}');
                return el && el.options && el.options.length > 1;
            }}
        """
        try:
            self.page.wait_for_function(js_wait_condition, timeout=timeout_ms)
        except Exception as e:
            raise CascadingDropdownError(
                f"Child dropdown '{child_selector}' did not populate options after selecting '{parent_value}' in '{parent_selector}' within {timeout_ms}ms."
            ) from e

        # Step 3 & 4: Select child option
        self.select_dropdown(child_selector, child_value)

    def upload_in_memory_file(
        self,
        selector: str,
        filename: str,
        mimetype: str,
        buffer_bytes: bytes
    ) -> None:
        """
        Injects an in-memory document file buffer into <input type="file"> via Playwright.
        Does NOT write the citizen document to disk.
        """
        if not self.page:
            raise BrowserAutomationError("Playwright page not set.")
        if not buffer_bytes or not isinstance(buffer_bytes, (bytes, bytearray)):
            raise FileInjectionError(f"Invalid in-memory buffer provided for '{selector}'.")

        loc = self.page.locator(selector)
        try:
            loc.wait_for(state="attached", timeout=5000)
            # Playwright set_input_files accepting dict with name, mimeType, buffer
            file_payload = {
                "name": filename,
                "mimeType": mimetype,
                "buffer": bytes(buffer_bytes),
            }
            loc.set_input_files(file_payload)
            loc.dispatch_event("input")
            loc.dispatch_event("change")
            logger.info(f"Successfully injected in-memory file payload into '{selector}': {filename}")
        except Exception as e:
            raise FileInjectionError(f"Playwright failed to attach in-memory file to '{selector}': {e}") from e

    def verify_dom_state(self, schema: FormSchema, state_mgr: FormStateManager) -> FormFillingResult:
        """
        Reads back values from the live page DOM to verify that injection succeeded.
        Ensures `#btnSubmit` was NOT triggered.
        """
        if not self.page:
            raise BrowserAutomationError("Playwright page not set.")

        fields_populated = []
        fields_missing = []
        validation_errors = []
        dom_values = {}

        for field_spec in schema.fields:
            selector = f"#{field_spec.id}"
            try:
                loc = self.page.locator(selector)
                if loc.count() == 0:
                    if field_spec.required:
                        fields_missing.append(field_spec.id)
                        validation_errors.append(f"Required field selector '{selector}' not found in DOM.")
                    continue

                if field_spec.type == "file":
                    # Check file attachment in DOM
                    has_files = self.page.eval_on_selector(
                        selector,
                        "el => el.files && el.files.length > 0"
                    )
                    if has_files:
                        file_name = self.page.eval_on_selector(selector, "el => el.files[0].name")
                        dom_values[field_spec.id] = f"[ATTACHED: {file_name}]"
                        fields_populated.append(field_spec.id)
                    else:
                        if field_spec.required:
                            fields_missing.append(field_spec.id)
                            validation_errors.append(f"File upload '{selector}' has no file attached.")
                elif field_spec.type == "select":
                    # Selected value/text
                    sel_info = self.page.eval_on_selector(
                        selector,
                        """el => ({
                            value: el.value,
                            text: el.options[el.selectedIndex] ? el.options[el.selectedIndex].text : ""
                        })"""
                    )
                    curr_val = sel_info["value"] or sel_info["text"]
                    dom_values[field_spec.id] = curr_val
                    if curr_val and not curr_val.startswith("--"):
                        fields_populated.append(field_spec.id)
                    else:
                        if field_spec.required:
                            fields_missing.append(field_spec.id)
                else:
                    # Text / Number inputs
                    curr_val = loc.input_value()
                    dom_values[field_spec.id] = curr_val
                    if curr_val and curr_val.strip():
                        fields_populated.append(field_spec.id)
                    else:
                        if field_spec.required:
                            fields_missing.append(field_spec.id)

            except Exception as e:
                validation_errors.append(f"Verification error for '{selector}': {e}")
                if field_spec.required:
                    fields_missing.append(field_spec.id)

        status = "POPULATED" if not fields_missing and not validation_errors else "PARTIALLY_POPULATED"
        if len(fields_populated) == 0:
            status = "FAILED"

        return FormFillingResult(
            status=status,
            form_url=schema.form_url,
            fields_populated=fields_populated,
            fields_missing=fields_missing,
            validation_errors=validation_errors,
            dom_values=dom_values,
            conflicts=[asdict(c) for c in state_mgr.conflicts],
        )


