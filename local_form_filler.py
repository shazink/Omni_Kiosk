def mask_pii_value(key: str, val: Any) -> str:
    """
    Redacts sensitive citizen PII (Aadhaar, phone, ration card, names) for privacy-safe logging.
    Aadhaar numbers are masked to '********1098'.
    """
    if val is None:
        return "None"
    s = str(val).strip()
    k_lower = key.lower()

    # Aadhaar (12 digits)
    if "aadhaar" in k_lower or "uid" in k_lower or re.fullmatch(r"\d{12}", s):
        digits = re.sub(r"\D", "", s)
        if len(digits) == 12:
            return f"********{digits[-4:]}"
        return "********" + s[-4:] if len(s) >= 4 else "********"

    # Phone / mobile
    if "phone" in k_lower or "mobile" in k_lower:
        digits = re.sub(r"\D", "", s)
        if len(digits) >= 4:
            return f"******{digits[-4:]}"
        return "******"

    # Ration card / Account numbers
    if "ration" in k_lower or "account" in k_lower or "bank" in k_lower:
        if len(s) > 4:
            return f"{'*' * (len(s) - 4)}{s[-4:]}"
        return "****"

    # Full Name
    if "name" in k_lower and not any(x in k_lower for x in ["service", "file", "district"]):
        parts = s.split()
        masked_parts = []
        for p in parts:
            if len(p) > 1:
                masked_parts.append(f"{p[0]}{'*' * (len(p) - 1)}")
            else:
                masked_parts.append(p)
        return " ".join(masked_parts)

    return s


def redact_text_pii(text: str) -> str:
    """Scans and redacts 12-digit Aadhaar UIDs and phone numbers from arbitrary text strings."""
    # 12-digit Aadhaar UID pattern
    text = re.sub(r"\b(\d{4})\s?(\d{4})\s?(\d{4})\b", r"********\3", text)
    # 10-digit mobile pattern
    text = re.sub(r"\b([6-9]\d{5})(\d{4})\b", r"******\2", text)
    return text


