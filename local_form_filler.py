class FieldPromptEngine:
    """Generates natural, contextual prompts for each required form field."""

    PROMPT_TEMPLATES: Dict[str, str] = {
        "txtApplicantName": "Please state your full name as it appears on your official ID.",
        "txtAadhaarNo": "Please provide your 12-digit Aadhaar UID number.",
        "ddlDistrict": "Please select your home district.",
        "ddlTaluk": "Please select your taluk.",
        "ddlVillage": "Please select your village office.",
        "txtRationCardNo": "Please provide your ration card number.",
        "txtAnnualIncome": "What is your annual family income in rupees?",
        "ddlPurpose": "What is the purpose of this certificate?",
        "fileAadhaar": "Please place your Aadhaar card on the document scanner tray.",
        "applicantName": "Please state your full name.",
        "aadhaarNo": "Please provide your 12-digit Aadhaar number.",
        "disabilityCategory": "Please specify your disability category.",
        "disabilityPercent": "What is your assessed percentage of disability?",
        "bankAccountNo": "Please provide your bank account number.",
        "ifscCode": "Please provide your bank IFSC code.",
    }

    @classmethod
    def generate_prompt(cls, field: FormField) -> str:
        # Check explicit template
        if field.id in cls.PROMPT_TEMPLATES:
            return cls.PROMPT_TEMPLATES[field.id]

        # Contextual prompt based on type and label
        label = field.label or field.id
        if field.type == "select":
            return f"Please select your {label}."
        elif field.type == "file":
            return f"Please place your {label} document on the scanner."
        elif field.type == "number":
            return f"Please state your {label}."
        else:
            return f"Please provide your {label}."


